# -*- coding: utf-8 -*-
"""核对业务表实际日期分布，判断诊断日期参数取值。"""
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, _ROOT)
from engine.db import get_conn          # noqa: E402

conn = get_conn()
cur = conn.cursor()


def line(title, sql):
    print("\n## %s" % title)
    cur.execute(sql)
    cols = [d[0] for d in cur.description]
    print("   ", cols)
    for r in cur.fetchall():
        print("   ", r)


line("交易日历 TP_EXCH_TRADE_DATE 范围",
     "SELECT MIN(TRADE_DATE) MN, MAX(TRADE_DATE) MX, COUNT(DISTINCT TRADE_DATE) DAYS, COUNT(*) CNT FROM INTERFACE.TP_EXCH_TRADE_DATE")

line("结算价 TC_CLEAR_PRICE 范围 / 最近5个交易日",
     "SELECT MIN(TRADE_DATE) MN, MAX(TRADE_DATE) MX, COUNT(DISTINCT TRADE_DATE) DAYS, COUNT(*) CNT FROM CLEAR.TC_CLEAR_PRICE")

line("结算价最近5个交易日的合约数",
     "SELECT TRADE_DATE, COUNT(*) FROM CLEAR.TC_CLEAR_PRICE GROUP BY TRADE_DATE ORDER BY TRADE_DATE DESC FETCH FIRST 5 ROWS ONLY")

line("递延费率 TC_DEFER_FEE_RATE 范围 / 最近5个交易日",
     "SELECT MIN(TRADE_DATE) MN, MAX(TRADE_DATE) MX, COUNT(DISTINCT TRADE_DATE) DAYS, COUNT(*) CNT FROM CLEAR.TC_DEFER_FEE_RATE")

line("递延费率 Ag(T+D) 最近5条",
     "SELECT TRADE_DATE, CONTRACT_ID, MEMBER_ID, DEFER_FEE, PAY_FLAG FROM CLEAR.TC_DEFER_FEE_RATE WHERE CONTRACT_ID='Ag(T+D)' ORDER BY TRADE_DATE DESC FETCH FIRST 5 ROWS ONLY")

line("客户持仓 TC_FTR_CLIENT_POSI_CLEAR 范围 / 最近5个结算日",
     "SELECT MIN(CLEAR_DATE) MN, MAX(CLEAR_DATE) MX, COUNT(DISTINCT CLEAR_DATE) DAYS, COUNT(*) CNT FROM CLEAR.TC_FTR_CLIENT_POSI_CLEAR")

line("客户持仓最近5个结算日",
     "SELECT CLEAR_DATE, COUNT(*) FROM CLEAR.TC_FTR_CLIENT_POSI_CLEAR GROUP BY CLEAR_DATE ORDER BY CLEAR_DATE DESC FETCH FIRST 5 ROWS ONLY")

line("持仓不足客户 016811/0000000168 的 Au(T+N1) 持仓（所有日期）",
     "SELECT CLEAR_DATE,CLIENT_ID,CONTRACT_ID,BUY_QTY,SELL_QTY FROM CLEAR.TC_FTR_CLIENT_POSI_CLEAR WHERE CLIENT_ID='0000000168' AND CONTRACT_ID='Au(T+N1)' ORDER BY CLEAR_DATE DESC FETCH FIRST 5 ROWS ONLY")

line("结算价 au2610C356 是否存在（任意日期）",
     "SELECT TRADE_DATE, CONTRACT_ID, CLEAR_PRICE FROM CLEAR.TC_CLEAR_PRICE WHERE CONTRACT_ID='au2610C356' ORDER BY TRADE_DATE DESC FETCH FIRST 5 ROWS ONLY")

conn.close()
